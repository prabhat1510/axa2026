package com.axa;

public class UnaryOperator {
    public static void main(String[] args) {
        int num=10;

        System.out.println(num++);//10 new value = 11
        System.out.println(++num);//12 new value = 12
        System.out.println(--num);//11 new value = 11
        System.out.println(num--);//11 new value 10
        System.out.println(num);
        System.out.println("**************************");



    }
}
