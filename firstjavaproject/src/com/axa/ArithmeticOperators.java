package com.axa;

public class ArithmeticOperators {

    public static void main(String[] args) {
        int a = 15;
        int b = 10;
        int res = a + b;
        System.out.println(res);
        res = a - b;
        System.out.println(res);
        res = a * b;
        System.out.println(res);
        res = a / b;// 15/10 =1
        System.out.println(res);
        res = a % b;//remainder 5
        System.out.println(res);

    }
}
