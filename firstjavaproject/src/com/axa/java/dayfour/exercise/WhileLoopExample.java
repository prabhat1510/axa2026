package com.axa.java.dayfour.exercise;

public class WhileLoopExample {
    public static void main(String[] args) {
        for(int i=1;i<=10;i++){
            System.out.println("Hello World");
        }
        System.out.println("****************");
        int count=0;
        while(count<5){
            System.out.println("Hello All");
            count++;
        }
        while(true){
            System.out.println("Hi All");
        }
    }
}
